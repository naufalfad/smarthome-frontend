export const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { glow?: boolean }
>(({ className, glow, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      'rounded-[22px] border border-slate-100/90 bg-white shadow-[0_8px_28px_-4px_rgba(112,118,150,0.07),0_4px_12px_-2px_rgba(112,118,150,0.04)] transition-all duration-200',
      glow && 'border-purple-200 shadow-purple-500/10',
      className
    )}
    {...props}
  />
));
Card.displayName = 'Card';

